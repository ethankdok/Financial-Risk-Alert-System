"""External AAER 0/1 research results are usable but never Taiwan production."""
from __future__ import annotations
import json
import tempfile
import unittest
from pathlib import Path
from app.services.financial_research.aaer_benchmark_reader import published_aaer_benchmark_summary as read

REPORT=(Path(__file__).resolve().parents[1]/
    "research/financial_ml/external_benchmark/results/real_aaer_supervised_holdout_report.json")

class ExternalAAERRealSupervisionTests(unittest.TestCase):
    def test_original_real_result_and_nondeceptive_holdout(self):
        if not REPORT.is_file():
            self.skipTest("Actual AAER research result generated by separate true-data GitHub job")
        x=read(REPORT)
        self.assertGreater(x["labeled_company_year_count"],30000)
        self.assertGreater(x["label_1"],100)
        self.assertGreater(x["label_0"],1000)
        self.assertEqual(x["label_1"]+x["label_0"],
                         x["labeled_company_year_count"])
        self.assertTrue(x["not_a_Taiwan_1785_prediction"])
        self.assertTrue(x["not_proof_of_clean_controls"])
        self.assertTrue(x["not_verified_individual_SEC_filings_as_of_each_date"])
        self.assertLess(x["holdout"]["precision"],0.2)
        self.assertEqual(sum(x["holdout"][k] for k in
            ("true_negative","false_positive","false_negative","true_positive")),
            x["holdout"]["samples"])

    def test_tampered_warning_rejected(self):
        x=json.loads(REPORT.read_text(encoding="utf-8"))
        x["NOT_TAIWAN_MODEL"]=False
        with tempfile.TemporaryDirectory() as tmp:
            p=Path(tmp)/"modified.json"
            p.write_text(json.dumps(x),encoding="utf-8")
            with self.assertRaisesRegex(ValueError,"quality disclaimer"):
                read(p)

    def test_tampered_confusion_counts_rejected(self):
        x=json.loads(REPORT.read_text(encoding="utf-8"))
        x["untouched_holdout_metrics"]["false_positive"]+=1
        with tempfile.TemporaryDirectory() as tmp:
            p=Path(tmp)/"modified.json"
            p.write_text(json.dumps(x),encoding="utf-8")
            with self.assertRaisesRegex(ValueError,"confusion matrix"):
                read(p)

if __name__=="__main__":
    unittest.main()
